const DICTS: Record<UiLang, Dict> = { de: DE, ru: RU, en: EN };

let cur: UiLang = 'de';

export function setUiLang(l: UiLang): void {
  if (DICTS[l]) cur = l;
}

export function uiLang(): UiLang {
  return cur;
}

/**
 * Gerätesprache erkennen (einmalig beim allerersten Start).
 * de → Deutsch, ru → Russisch, en → Englisch — ALLES ANDERE:
 * Russisch (bewusster Fallback, Anforderung: „Standard auf Russisch“).
 */
export function detectUiLang(): UiLang {
  try {
    const langs: string[] = [
      ...(navigator.languages ?? []),
      navigator.language || '',
    ];
    for (const raw of langs) {
      const l = (raw || '').toLowerCase();
      if (l.startsWith('de')) return 'de';
      if (l.startsWith('ru')) return 'ru';
      if (l.startsWith('en')) return 'en';
    }
  } catch {
    /* ignore */
  }
  return 'ru';
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[cur][key] ?? DICTS.de[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return s;
}

