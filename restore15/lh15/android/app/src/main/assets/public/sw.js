/* LearnHarness PWA — minimaler, robuster Service Worker
 * Strategien:
 *  - Navigation (index.html): network-first, Offline-Fallback aus Cache
 *  - Gleichoriginige Assets (gehasht): stale-while-revalidate
 *  - Fremdorigin (googleapis.com etc.): unberuehrt -> Streaming/API bleibt direkt
 *  - Nicht-GET (POST auf Gemini-API): unberuehrt
 */
const CACHE = 'lh-pwa-v1';
const CORE = ['./', './index.html'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(CORE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  let url;
  try {
    url = new URL(req.url);
  } catch {
    return;
  }
  if (url.origin !== self.location.origin) return; // Gemini-API & Co. direkt lassen

  // Navigation: frisch ziehen, offline aus Cache bedienen
  if (req.mode === 'navigate' || (req.headers.get('accept') || '').includes('text/html')) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./index.html', copy));
          return res;
        })
        .catch(() => caches.match('./index.html'))
    );
    return;
  }

  // Gehashte Assets: sofort aus Cache, parallel aktualisieren
  event.respondWith(
    caches.match(req).then((hit) => {
      const net = fetch(req)
        .then((res) => {
          if (res && res.status === 200 && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => hit);
      return hit || net;
    })
  );
});
